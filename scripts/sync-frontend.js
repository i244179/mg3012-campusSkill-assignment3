#!/usr/bin/env node
/**
 * scripts/sync-frontend.js
 *
 * Copies the ABI and the deployed address of CampusSkill from the Truffle
 * build artifact (build/contracts/CampusSkill.json) into src/contract-config.js,
 * so the frontend always uses exactly what Truffle compiled and deployed.
 *
 * When to run it: after every `truffle migrate` (the npm scripts
 * `npm run migrate` and `npm run migrate:reset` run it automatically).
 *
 *   node scripts/sync-frontend.js
 *
 * It never invents an address: if the contract has not been deployed to the
 * running Ganache network, it stops with an error.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const ARTIFACT = path.join(ROOT, "build", "contracts", "CampusSkill.json");
const OUTPUT = path.join(ROOT, "src", "contract-config.js");
const truffleConfig = require(path.join(ROOT, "truffle-config.js"));

function fail(message) {
  console.error(`\n  sync-frontend: ${message}\n`);
  process.exit(1);
}

async function rpc(url, method, params = []) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
  });
  const json = await response.json();
  if (json.error) throw new Error(json.error.message);
  return json.result;
}

(async () => {
  const dev = truffleConfig.networks && truffleConfig.networks.development;
  if (!dev) fail("truffle-config.js has no 'development' network.");
  const rpcUrl = `http://${dev.host}:${dev.port}`;

  if (!fs.existsSync(ARTIFACT)) {
    fail(`${path.relative(ROOT, ARTIFACT)} not found. Run "npx truffle compile" and "npx truffle migrate --network development" first.`);
  }
  const artifact = JSON.parse(fs.readFileSync(ARTIFACT, "utf8"));

  // Ask the running Ganache which network it is, so we pick the matching deployment.
  let networkId, chainId;
  try {
    networkId = await rpc(rpcUrl, "net_version");
    chainId = parseInt(await rpc(rpcUrl, "eth_chainId"), 16);
  } catch (err) {
    fail(`cannot reach Ganache at ${rpcUrl} (${err.message}). Start Ganache first.`);
  }

  const deployment = artifact.networks && artifact.networks[networkId];
  if (!deployment || !deployment.address) {
    fail(`CampusSkill is not deployed on Ganache network ${networkId}. Run "npx truffle migrate --network development" (add --reset to redeploy).`);
  }

  // Make sure the address really holds contract bytecode on this Ganache chain.
  const code = await rpc(rpcUrl, "eth_getCode", [deployment.address, "latest"]);
  if (!code || code === "0x") {
    fail(`no contract code at ${deployment.address} on this Ganache chain (was Ganache restarted?). Run "npx truffle migrate --network development --reset".`);
  }

  const config = {
    contractName: artifact.contractName,
    sourceFile: path.basename(artifact.sourcePath || "SmartContract.sol"),
    compiler: artifact.compiler && artifact.compiler.version,
    address: deployment.address,
    transactionHash: deployment.transactionHash || null,
    networkId: String(networkId),
    chainId,
    rpcUrl,
    artifactUpdatedAt: artifact.updatedAt,
    abi: artifact.abi,
  };

  const banner = [
    "// AUTO-GENERATED by scripts/sync-frontend.js - do not edit by hand.",
    `// Source: build/contracts/${artifact.contractName}.json (Truffle artifact)`,
    `// Generated: ${new Date().toISOString()}`,
    "// Re-run `npm run sync` (or `npm run migrate`) after every truffle migrate.",
  ].join("\n");
  fs.writeFileSync(OUTPUT, `${banner}\nwindow.CAMPUSSKILL_CONFIG = ${JSON.stringify(config, null, 2)};\n`);

  console.log("\n  Frontend synced with the Truffle deployment");
  console.log("  -------------------------------------------");
  console.log(`  Contract        : ${config.contractName} (${config.sourceFile})`);
  console.log(`  Address         : ${config.address}`);
  console.log(`  Ganache network : id ${config.networkId}, chain ${config.chainId}, ${rpcUrl}`);
  console.log(`  ABI entries     : ${config.abi.length}`);
  console.log(`  Written to      : ${path.relative(ROOT, OUTPUT)}\n`);
})();
